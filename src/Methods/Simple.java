package Methods;



public class Simple {

    // Create a Methods
    static void print2table() {
        for (int i = 1; i <= 10; i++)
        {
            int ans = (i*2);
            System.out.println("-> " + ans);
        }

    }

    static void main(String[] args) {

      // Method call
        print2table();


    }
}
