package Loops;

public class print_Number {
    static void main(String[] args) {
        //First loop

        for (int i = 1; i <= 10; i++)
        {
            System.out.println(i);
        }
        System.out.println();

        //Second loop
        for (int j = 1; j <= 10; j++)
        {
            System.out.println("Aman:");
        }
        System.out.println();

        //Third loop
        for (int k = 1; k <= 10; k +=2)
        {
            System.out.println(k);
        }
        System.out.println();
    }
}
